def filter_prediction_features(
    competition: str = "all", season: str = "all"
) -> pl.DataFrame:
    """Filter precomputed prediction features by competition and season."""
    prediction_features_df = get_prediction_features_df()
    if prediction_features_df.is_empty():
        return prediction_features_df

    filtered = prediction_features_df
    if competition and competition != "all":
        filtered = filtered.filter(pl.col("competition_name") == competition)
    if season and season != "all":
        filtered = filtered.filter(pl.col("season_name") == season)
    return filtered


def compute_prediction_r2(
    df: pl.DataFrame, feature_cols: list[str]
) -> Optional[float]:
    """Fit a small OLS model and return in-sample R²."""
    if df.is_empty():
        return None

    usable_features = [feature for feature in feature_cols if feature in df.columns]
    if not usable_features:
        return None

    clean = df.select(usable_features + ["goal_diff"]).drop_nulls()
    if clean.height <= len(usable_features):
        return None

    X = clean.select(usable_features).to_numpy()
    y = clean["goal_diff"].to_numpy()
    X = np.column_stack([np.ones(X.shape[0]), X])
    coeffs = np.linalg.lstsq(X, y, rcond=None)[0]
    y_pred = X @ coeffs

    ss_res = np.sum((y - y_pred) ** 2)
    ss_tot = np.sum((y - np.mean(y)) ** 2)
    if ss_tot == 0:
        return None
    return float(1 - (ss_res / ss_tot))


def compute_halftime_failure_rate(df: pl.DataFrame) -> Optional[float]:
    """Share of halftime leaders that fail to win by full time."""
    if df.is_empty():
        return None

    halftime_leads = df.filter(pl.col("halftime_goal_diff") != 0)
    if halftime_leads.is_empty():
        return None

    failures = halftime_leads.filter(
        ((pl.col("halftime_goal_diff") > 0) & (pl.col("goal_diff") <= 0))
        | ((pl.col("halftime_goal_diff") < 0) & (pl.col("goal_diff") >= 0))
    )
    return float(failures.height / halftime_leads.height)


