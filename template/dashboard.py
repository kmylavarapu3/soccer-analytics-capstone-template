@callback(
    Output("xg-performance-chart", "figure"),
    Input("tactical-competition-filter", "value"),
)
def update_xg_performance(competition):
    if not competition:
        return go.Figure()

    try:
        comp_matches = matches_df.filter(pl.col("competition_name") == competition)

        data = []
        for team in all_teams:
            team_matches = comp_matches.filter(
                (pl.col("home_team") == team) | (pl.col("away_team") == team)
            )
            if team_matches.is_empty():
                continue

            total_goals = 0
            total_xg = 0
            count = 0

            for row in team_matches.iter_rows(named=True):
                match_id = row["match_id"]
                home_team = row["home_team"]
                home_score = row["home_score"]
                away_score = row["away_score"]

                if home_team == team:
                    total_goals += home_score
                else:
                    total_goals += away_score

                shots = events_df.filter(
                    (pl.col("match_id") == match_id)
                    & (pl.col("team") == team)
                    & (pl.col("type") == "Shot")
                    & (pl.col("shot_statsbomb_xg").is_not_null())
                )
                total_xg += shots["shot_statsbomb_xg"].sum()
                count += 1

            if count > 0:
                data.append(
                    {
                        "team": team,
                        "goals": total_goals,
                        "xg": total_xg,
                    }
                )

        if data:
            df = pd.DataFrame(data)
            fig = go.Figure()

            fig.add_trace(
                go.Scatter(
                    x=df["xg"],
                    y=df["goals"],
                    mode="markers",
                    marker=dict(size=10, color=THEME["colors"]["accent"]),
                    text=df["team"],
                    hoverinfo="text+x+y",
                )
            )

            # Add diagonal line (goals = xG)
            min_val = min(df["xg"].min(), df["goals"].min())
            max_val = max(df["xg"].max(), df["goals"].max())
            fig.add_trace(
                go.Scatter(
                    x=[min_val, max_val],
                    y=[min_val, max_val],
                    mode="lines",
                    line=dict(dash="dash", color=THEME["colors"]["text_muted"]),
                    name="Expected (Goals = xG)",
                )
            )

            fig.update_layout(
                template=plotly_template,
                title=f"{competition} - Goals vs Expected Goals (xG)",
                xaxis_title="Total Expected Goals (xG)",
                yaxis_title="Actual Goals Scored",
                height=500,
                margin=dict(l=60, r=20, t=60, b=60),
            )

            return fig

        return go.Figure()
    except Exception:
        return go.Figure()


