@callback(
    Output("lead-collapse-chart", "figure"),
    [
        Input("prediction-competition-filter", "value"),
        Input("prediction-season-filter", "value"),
    ],
)
def update_lead_collapse_chart(competition, season):
    df = get_prediction_features_df()
    if df.is_empty():
        return empty_dashboard_figure(
            "Halftime Lead Failure by Lead Size",
            "Prediction features are not available yet.",
        )

    filtered = filter_prediction_features(competition, season)
    if filtered.is_empty():
        return empty_dashboard_figure(
            "Halftime Lead Failure by Lead Size",
            "No matches found for the selected Competition and Season.",
        )

    halftime_leads = filtered.filter(pl.col("halftime_goal_diff") != 0)
    if halftime_leads.is_empty():
        return empty_dashboard_figure(
            "Halftime Lead Failure by Lead Size",
            "No halftime leads found for the current filter.",
        )

    collapse_df = (
        halftime_leads.with_columns(
            [
                pl.col("halftime_goal_diff").abs().alias("abs_halftime_lead"),
                pl.when(pl.col("halftime_goal_diff").abs() >= 2)
                .then(pl.lit("2+ goal lead"))
                .otherwise(pl.lit("1 goal lead"))
                .alias("lead_bucket"),
                (
                    ((pl.col("halftime_goal_diff") > 0) & (pl.col("goal_diff") <= 0))
                    | ((pl.col("halftime_goal_diff") < 0) & (pl.col("goal_diff") >= 0))
                )
                .cast(pl.Float64)
                .alias("leader_failed"),
            ]
        )
        .group_by("lead_bucket")
        .agg(
            [
                pl.len().alias("matches"),
                pl.col("leader_failed").mean().alias("failure_rate"),
            ]
        )
        .with_columns(
            pl.when(pl.col("lead_bucket") == "1 goal lead")
            .then(pl.lit(0))
            .otherwise(pl.lit(1))
            .alias("bucket_order")
        )
        .sort("bucket_order")
    )

    chart_df = collapse_df.to_pandas()
    fig = px.bar(
        chart_df,
        x="lead_bucket",
        y="failure_rate",
        text="matches",
        color="failure_rate",
        color_continuous_scale="Reds",
        height=400,
    )
    fig.update_layout(
        template=plotly_template,
        xaxis_title="Halftime Lead Size",
        yaxis_title="Failure Rate",
        margin=dict(l=60, r=20, t=40, b=60),
        showlegend=False,
    )
    fig.update_yaxes(tickformat=".0%")
    fig.update_traces(texttemplate="%{text} matches", textposition="outside")
    return fig


